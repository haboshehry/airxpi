def leases():
    out = {}
    for line in c.read_text("/var/lib/misc/dnsmasq.leases").splitlines():
        parts = line.split()
        if len(parts) >= 4:
            out[parts[1].lower()] = {"ip": parts[2], "name": parts[3]}
    return out


def wifi_stations():
    stations = {}
    rc, out = c.run(["iw", "dev", "wlan0", "station", "dump"], timeout=15)
    if rc != 0:
        return stations
    current = None
    for line in out.splitlines():
        match = re.match(r"Station ([0-9a-f:]{17})", line.strip())
        if match:
            current = match.group(1).lower()
            stations[current] = {}
            continue
        if current and ":" in line:
            key, _, value = line.strip().partition(":")
            stations[current][key.strip()] = value.strip()
    return stations


def clients():
    neigh = {}
    rc, out = c.run(["ip", "-4", "neigh", "show", "dev", BRIDGE], timeout=15)
    if rc == 0:
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 5 and "lladdr" in parts:
                ip = parts[0]
                mac = parts[parts.index("lladdr") + 1].lower()
                state = parts[-1]
                neigh[mac] = {"ip": ip, "mac": mac, "state": state}
    by_ip = leases()
    stations = wifi_stations()
    result = []
    for mac, item in neigh.items():
        lease = by_ip.get(item["ip"], {})
        station = stations.get(mac, {})
        signal = station.get("signal", "")
        result.append({
            "mac": mac,
            "ip": item["ip"],
            "name": lease.get("name") or "",
            "online": item["state"] != "FAILED",
            "wifi": bool(station),
            "signal_dbm": int(re.sub(r"[^0-9-]", "", signal)) if signal else None,
            "rx": station.get("rx bytes", ""),
            "tx": station.get("tx bytes", ""),
        })
    result.sort(key=lambda r: tuple(int(x) for x in r["ip"].split(".")) if r["ip"].count(".") == 3 else (0,))
    return result


def snapshot(cfg=None):
    cfg = cfg or c.config()
    wifi = cfg["wifi"]
    lan_ip = c.ip_of(BRIDGE)
    return {
        "wan": wan_state(cfg),
        "lan": {
            "iface": BRIDGE,
            "ip": lan_ip,
            "cidr": cfg["lan"]["cidr"],
            "ethernet": LAN_ETH in c.interfaces(),
            "members": [n for n, v in c.interfaces().items() if v.get("kind") == "ethernet" and n == LAN_ETH],
        },
        "wifi": {
            "enabled": bool(wifi.get("enabled")),
            "running": wifi_running(),
            "ssid": c.sanitize_text(wifi.get("ssid"), 32),
            "channel": int(wifi.get("channel") or 6),
            "country": (wifi.get("country") or "").upper(),
            "hidden": bool(wifi.get("hidden")),
            "clients": len([s for s in wifi_stations()]),
            "psk_set": c.valid_psk(wifi.get("passphrase")),
        },
        "clients": clients(),
        "hostname": c.hostname(),
        "uptime": int(float(c.read_text("/proc/uptime", "0").split()[0] or 0)),
        "config": cfg,
    }


