def nft_ruleset(cfg):
    lan_net = c.lan_network()
    mark = "0x1a1"
    wan_access = bool(cfg["panel"].get("wan_access", True))
    panel_guard = "iifname != \"lo\" tcp dport { 8079, 8086, 8088, 8090 } drop"
    input_lines = [panel_guard]
    if not wan_access:
        wan = wan_iface(cfg)
        if wan:
            input_lines.append('iifname "%s" tcp dport 80 drop' % wan)
    nat = [
        "table ip airxpi_nat {",
        "\tchain postrouting {",
        "\t\ttype nat hook postrouting priority srcnat; policy accept;",
        "\t\t# LAN -> internet; traffic marked by vpnexit is SNATed to the",
        "\t\t# tunnel address by vpnexit itself, so it must be left alone",
        '\t\toifname != "%s" ip saddr %s meta mark != %s masquerade' % (BRIDGE, lan_net, mark),
        "\t}",
        "}",
    ]
    return "\n".join([
        "table inet airxpi {",
        "\tchain input {",
        "\t\ttype filter hook input priority filter; policy accept;",
        "\t\t" + "\n\t\t".join(input_lines),
        "\t}",
        "\tchain forward {",
        "\t\ttype filter hook forward priority filter; policy accept;",
        "\t\tct state established,related accept",
        '\t\tiifname "%s" accept' % BRIDGE,
        "\t}",
        "}",
    ] + nat) + "\n"


def nft_apply(cfg):
    text = nft_ruleset(cfg)
    path = os.path.join(c.RUN_DIR, "airxpi.nft")
    c.write_atomic(path, text, 0o600)
    rc, out = c.run(["nft", "-c", "-f", path], timeout=20)
    if rc != 0:
        c.log("nft check failed: %s" % out[:300])
        return False
    batch = ""
    if c.run(["nft", "list", "table", "inet", "airxpi"], timeout=10)[0] == 0:
        batch += "delete table inet airxpi\n"
    if c.run(["nft", "list", "table", "ip", "airxpi_nat"], timeout=10)[0] == 0:
        batch += "delete table ip airxpi_nat\n"
    bpath = os.path.join(c.RUN_DIR, "airxpi-apply.nft")
    c.write_atomic(bpath, batch + text, 0o600)
    rc, out = c.run(["nft", "-f", bpath], timeout=20)
    if rc != 0:
        c.log("nft apply failed: %s" % out[:300])
        return False
    return True


