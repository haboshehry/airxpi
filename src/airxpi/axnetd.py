#!/usr/bin/env python3
"""axnetd - network manager for the AirXPi appliance.

The box has exactly one job on the network:

    WAN  = eth0 (cable) or a USB tether (iPhone ``usb0`` / Android ``usb0``/``enx*``)
    LAN  = br0, a bridge of the USB Ethernet port (eth1) and the on-board Wi-Fi AP

Everything else - DHCP server, NAT, hostapd, Avahi scope - is derived from
``/etc/airxpi/airxpi.json`` by :func:`apply`.  The daemon exposes a small
localhost-only JSON API (port 8079) that the web panel and the HDMI UI use, so
both front-ends always share one implementation.

Run as root.  ``python3 -m airxpi.axnetd apply`` is safe to call from udev or
systemd at any time.
"""

import json
import os
import random
import re
import signal
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

from . import common as c

HOSTAPD_CONF = "/etc/hostapd/hostapd.conf"
DNSMASQ_CONF = "/etc/dnsmasq.d/airxpi.conf"
DHCPCD_CONF = "/etc/dhcpcd.conf"
AVAHI_CONF = "/etc/avahi/avahi-daemon.conf"
SYSCTL_CONF = "/etc/sysctl.d/90-airxpi.conf"
BRIDGE = "br0"
LAN_ETH = "eth1"

HOSTAPD_MARK = "# generated by axnetd - do not edit, use the panel\n"
DNSMASQ_MARK = "# generated by axnetd\n"
DHCPCD_MARK = "# airxpi block - generated by axnetd\n"

LOCK = threading.Lock()


# --------------------------------------------------------------------------
# uplink detection
# --------------------------------------------------------------------------
def wan_iface(cfg=None):
    """Return the interface that currently carries the internet uplink."""
    cfg = cfg or c.config()
    mode = (cfg["wan"].get("mode") or "auto").lower()
    found = c.interfaces()
    cands = c.wan_candidates()

    def usable(name):
        info = found.get(name)
        return bool(info) and info.get("operstate", "").lower() in ("up", "unknown")

    if mode == "eth0":
        return "eth0" if "eth0" in found else ""
    if mode == "usb":
        for name in cands["usb"]:
            if usable(name):
                return name
        return cands["usb"][0] if cands["usb"] else ""
    # auto: cable first (cheap, stable), then USB tethering
    for name in cands["ethernet"]:
        if usable(name):
            return name
    for name in cands["usb"]:
        if usable(name):
            return name
    return ""


def wan_state(cfg=None):
    cfg = cfg or c.config()
    iface = wan_iface(cfg)
    info = c.interfaces().get(iface, {})
    route = c.default_route()
    return {
        "iface": iface,
        "kind": info.get("kind", ""),
        "ip": info.get("ip", ""),
        "mode": cfg["wan"].get("mode", "auto"),
        "route": route.get("dev", ""),
        "up": bool(info.get("ip")),
        "candidates": c.wan_candidates(),
    }


