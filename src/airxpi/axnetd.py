def random_passphrase(length=10):
    alphabet = "abcdefghjkmnpqrstuvwxyz23456789"
    return "".join(random.choice(alphabet) for _ in range(length))


def set_wifi(payload):
    cfg = c.config()
    wifi = cfg["wifi"]
    errors = []
    if "ssid" in payload:
        raw_ssid = str(payload.get("ssid") or "")
        ssid = c.sanitize_text(raw_ssid, 32)
        if len(raw_ssid) > 32:
            errors.append("SSID must be 1-32 printable characters")
        elif not c.valid_ssid(ssid) or len(ssid) < 1:
            errors.append("SSID must be 1-32 printable characters")
        else:
            wifi["ssid"] = ssid
    if "passphrase" in payload:
        psk = str(payload.get("passphrase") or "")
        if psk and not c.valid_psk(psk):
            errors.append("Passphrase must be 8-63 characters, or empty for an open network")
        else:
            wifi["passphrase"] = psk
    if "channel" in payload:
        if not c.valid_channel(payload.get("channel")):
            errors.append("Channel must be 1-13 (2.4 GHz)")
        else:
            wifi["channel"] = int(payload["channel"])
    if "country" in payload:
        country = str(payload.get("country") or "").upper()
        if country and not c.valid_country(country):
            errors.append("Country must be a two letter code")
        else:
            wifi["country"] = country
    if "enabled" in payload:
        wifi["enabled"] = bool(payload.get("enabled"))
    if "hidden" in payload:
        wifi["hidden"] = bool(payload.get("hidden"))
    if "max_clients" in payload:
        try:
            wifi["max_clients"] = max(1, min(64, int(payload["max_clients"])))
        except (TypeError, ValueError):
            errors.append("max_clients must be a number")
    if errors:
        return {"ok": False, "error": "; ".join(errors)}, cfg
    if wifi.get("enabled") and (wifi.get("passphrase") or "") and not c.valid_psk(wifi["passphrase"]):
        return {"ok": False, "error": "set a passphrase of 8-63 characters, or leave it empty"}, cfg
    c.save_config(cfg)
    apply(cfg)
    return {"ok": True, "wifi": snapshot(cfg)["wifi"]}, cfg


def set_wan(payload):
    cfg = c.config()
    mode = str(payload.get("mode") or "auto").lower()
    if mode not in ("auto", "eth0", "usb"):
        return {"ok": False, "error": "mode must be auto, eth0 or usb"}, cfg
    cfg["wan"]["mode"] = mode
    c.save_config(cfg)
    apply(cfg)
    return {"ok": True, "wan": snapshot(cfg)["wan"]}, cfg


def set_lan(payload):
    cfg = c.config()
    if "ethernet" in payload:
        cfg["lan"]["ethernet"] = bool(payload["ethernet"])
    if "cidr" in payload:
        cidr = str(payload["cidr"])
        if not re.match(r"^\d+\.\d+\.\d+\.\d+/24$", cidr):
            return {"ok": False, "error": "cidr must be a /24 address"}, cfg
        cfg["lan"]["cidr"] = cidr
    c.save_config(cfg)
    apply(cfg)
    return {"ok": True, "lan": snapshot(cfg)["lan"]}, cfg


def set_device(payload):
    cfg = c.config()
    changed = {}
    if "name" in payload:
        name = c.sanitize_text(payload["name"], 32)
        if not name:
            return {"ok": False, "error": "name required"}
        cfg["device"]["name"] = name
        cfg["airplay"]["name"] = name
        changed["name"] = name
    if "language" in payload and str(payload["language"]) in ("en", "fa"):
        cfg["device"]["language"] = str(payload["language"])
    if "wan_access" in payload:
        cfg["panel"]["wan_access"] = bool(payload["wan_access"])
    c.save_config(cfg)
    apply(cfg)
    if changed.get("name"):
        # keep the AirPlay service name in step with the appliance name
        try:
            import urllib.request
            body = json.dumps({"name": changed["name"], "force": True}).encode()
            req = urllib.request.Request(
                "http://127.0.0.1:%d/api/config" % c.AIRPLAY_PORT,
                data=body, headers={"Content-Type": "application/json"}, method="POST")
            urllib.request.urlopen(req, timeout=20).read()
        except Exception as exc:  # noqa: BLE001
            c.log("airplay rename failed: %r" % (exc,))
    return {"ok": True, "device": cfg["device"]}, cfg


