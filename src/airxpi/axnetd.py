def write_dhcpcd(cfg):
    """Keep dhcpcd away from the LAN side and the bridge."""
    # Allow everything except the LAN side.  The old positive allow-list
    # ("eth0 usb0 enx* usb*") never matched a tethered phone, because the Pi
    # names it eth2/eth3, so the uplink got no lease and tethering looked dead.
    lines = [
        DHCPCD_MARK,
        "hostname",
        "clientid",
        "persistent",
        "option rapid_commit",
        "option domain_name_servers, domain_name, domain_search, host_name",
        "option classless_static_routes",
        "option interface_mtu",
        "require dhcp_server_identifier",
        "slaac private",
        "# LAN side and tunnels must never get a DHCP lease" + (
            " (br0 is the client in bridge mode)" if wifi_mode(cfg) == "bridge" else ""),
        "denyinterfaces %s %s wlan0 axtun* axpi0 ap0" % (
            "" if wifi_mode(cfg) == "bridge" else BRIDGE, LAN_ETH),
        "allowinterfaces *",
    ]
    body = c.read_text(DHCPCD_CONF)
    keep = []
    inside = False
    for line in body.splitlines():
        if line.strip() == DHCPCD_MARK.strip():
            inside = True
            continue
        if inside and line.strip() == "# end airxpi block":
            inside = False
            continue
        if not inside:
            keep.append(line)
    text = "\n".join(keep).rstrip() + "\n\n" + "\n".join(lines) + "\n# end airxpi block\n"
    if text != body:
        c.write_atomic(DHCPCD_CONF, text, 0o644)
        return True
    return False


def hostapd_config(cfg):
    """Render hostapd.conf for a Pi 3B (2.4 GHz, 802.11n, WPA2-CCMP).

    The extra keys are not decoration: phones that refuse to join an otherwise
    valid hostapd are almost always hitting one of them.

      * ``ieee80211w=0`` - WPA2 with PMF *capable* is fine, but some Android
        builds fail the 4-way handshake when the AP advertises PMF as required.
        The default in hostapd already drifts between releases, so pin it.
      * ``disassoc_low_ack=0`` - the Pi's radio reports a low ACK count as soon
        as a phone idles; disassociating on that is what "my phone connects for
        a second and drops" looks like.
      * ``ap_max_inactivity`` - phones sleep aggressively; 5 minutes of silence
        must not delete their station entry while DHCP is still running.
      * ``country_code`` + ``ieee80211d`` - without a regulatory domain the
        driver refuses channels 12/13 and some clients refuse the BSS entirely.
    """
    wifi = cfg["wifi"]
    ssid = c.sanitize_text(wifi.get("ssid"), 32) or "AirXPi"
    psk = wifi.get("passphrase") or ""
    country = (wifi.get("country") or "").upper()
    channel = int(wifi.get("channel") or 6)
    if c.valid_country(country) and country in ("US", "CA", "MX", "BR") and channel > 11:
        channel = 11  # these domains do not allow 12/13; hostapd would refuse
    lines = [
        HOSTAPD_MARK.rstrip("\n"),
        "interface=wlan0",
        "bridge=%s" % BRIDGE,
        "driver=nl80211",
        "ctrl_interface=/run/hostapd",
        "ctrl_interface_group=0",
        "logger_syslog=-1",
        "logger_syslog_level=2",
        "ssid=%s" % ssid,
        "utf8_ssid=1",
    ]
    if c.valid_country(country):
        lines.append("country_code=%s" % country)
    lines += [
        "ieee80211d=%d" % (1 if c.valid_country(country) else 0),
        "hw_mode=g",
        "channel=%d" % channel,
        "beacon_int=100",
        "dtim_period=2",
        "max_num_sta=%d" % max(1, min(64, int(wifi.get("max_clients") or 16))),
        "auth_algs=1",
        "wmm_enabled=1",
        "ieee80211n=%d" % (1 if wifi.get("ieee80211n", True) else 0),
        "ignore_broadcast_ssid=%d" % (1 if wifi.get("hidden") else 0),
        "macaddr_acl=0",
        "ap_isolate=0",
        "ap_max_inactivity=600",
        "disassoc_low_ack=0",
        "skip_inactivity_poll=0",
    ]
    if psk:
        # a configured passphrase means WPA2; no passphrase means an open network
        lines += [
            "wpa=2",
            "wpa_key_mgmt=WPA-PSK",
            "wpa_pairwise=CCMP",
            "rsn_pairwise=CCMP",
            "wpa_group_rekey=600",
            "ieee80211w=0",
            "wpa_passphrase=%s" % psk,
        ]
    return "\n".join(lines) + "\n"


def check_hostapd(path):
    """Validate a hostapd config before restarting the service.

    ``hostapd -t`` parses the file and the driver capabilities without touching
    the live interface, so a bad channel/passphrase becomes an error message in
    the panel instead of a service that never becomes active.
    """
    if not os.path.exists("/usr/sbin/hostapd"):
        return 0, "hostapd is not installed"
    # hostapd 2.10 (Debian) has no config-test mode: "-t" means "timestamps",
    # so `hostapd -t -c file` prints the usage text and exits non-zero.  That
    # made every apply() fail with "hostapd rejected the configuration" and the
    # access point never started.  Check the essentials here and let the unit
    # start be the real validation - unit_failure() reports the driver error.
    body = c.read_text(path)
    for key in ("interface=", "ssid=", "hw_mode=", "channel="):
        if key not in body:
            return 1, "hostapd.conf is missing %s" % key
    return 0, "ok"


def write_hostapd(cfg):
    text = hostapd_config(cfg)
    changed = c.read_text(HOSTAPD_CONF) != text
    if changed:
        c.write_atomic(HOSTAPD_CONF, text, 0o600)
    return changed


def write_dnsmasq(cfg):
    lan = cfg["lan"]
    lines = [
        DNSMASQ_MARK.rstrip("\n"),
        "interface=%s" % BRIDGE,
        "bind-dynamic",
        "domain-needed",
        "bogus-priv",
        "expand-hosts",
        "dhcp-authoritative",
        "dhcp-range=%s,%s,255.255.255.0,%s" % (lan["dhcp_start"], lan["dhcp_end"], lan["lease"]),
        "dhcp-option=option:router,%s" % lan["cidr"].split("/")[0],
        "dhcp-option=option:dns-server,%s" % lan["cidr"].split("/")[0],
        "dhcp-leasefile=/var/lib/misc/dnsmasq.leases",
        "cache-size=1000",
        "log-async=10",
        "# never serve DNS/DHCP to the uplink",
        "except-interface=eth0",
        "except-interface=usb0",
        "except-interface=lo",
    ]
    c.write_atomic(DNSMASQ_CONF, "\n".join(lines) + "\n", 0o644)


def write_sysctl():
    text = "\n".join([
        "# AirXPi: routing + IPv6 off (the VPN exit is IPv4 only, and IPv6 on the",
        "# LAN would bypass the tunnel)",
        "net.ipv4.ip_forward=1",
        "net.ipv4.conf.all.src_valid_mark=1",
        "net.ipv6.conf.all.disable_ipv6=1",
        "net.ipv6.conf.default.disable_ipv6=1",
        "net.ipv4.conf.all.rp_filter=0",
        "net.ipv4.conf.default.rp_filter=0",
        "net.ipv4.tcp_mtu_probing=1",
        "",
    ])
    if c.read_text(SYSCTL_CONF) != text:
        c.write_atomic(SYSCTL_CONF, text, 0o644)
        c.run(["sysctl", "-q", "-p", SYSCTL_CONF], timeout=20)


def write_avahi(cfg):
    """Advertise AirPlay on the interfaces a sender can actually reach.

    The LAN bridge is the normal case; the uplink is included because an
    iPhone that shares its connection over USB is also the device that wants
    to stream to us.
    """
    names = [BRIDGE]
    wan = wan_iface(cfg)
    if wan:
        names.append(wan)
    names += [n for n in c.usb_net_ifaces() if n not in names]
    text = "\n".join([
        "# generated by axnetd",
        "[server]",
        "use-ipv4=yes",
        "use-ipv6=no",
        "allow-interfaces=%s" % ",".join(names),
        "ratelimit-interval-usec=1000000",
        "ratelimit-burst=1000",
        "[wide-area]",
        "[publish]",
        "publish-hinfo=no",
        "publish-workstation=no",
        "[reflector]",
        "[rlimits]",
        "",
    ])
    if c.read_text(AVAHI_CONF) != text:
        c.write_atomic(AVAHI_CONF, text, 0o644)
        return True
    return False


