class Handler(BaseHTTPRequestHandler):
    server_version = "axnetd/1.0"

    def log_message(self, *args):
        return

    def _json(self, obj, code=200):
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Cache-Control", "no-store")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        try:
            self.wfile.write(body)
        except OSError:
            pass

    def _body(self):
        try:
            size = int(self.headers.get("Content-Length") or 0)
            if not size:
                return {}
            return json.loads(self.rfile.read(size).decode("utf-8", "replace") or "{}")
        except (ValueError, OSError):
            return {}

    def do_GET(self):
        path = self.path.split("?")[0]
        if path == "/state":
            return self._json({"ok": True, "state": snapshot()})
        if path == "/clients":
            return self._json({"ok": True, "clients": clients()})
        if path == "/health":
            return self._json({"ok": True, "service": "axnetd"})
        return self._json({"ok": False, "error": "not found"}, 404)

    def do_POST(self):
        path = self.path.split("?")[0]
        body = self._body()
        if path == "/wifi":
            result, _ = set_wifi(body)
            return self._json(result, 200 if result.get("ok") else 400)
        if path == "/wan":
            result, _ = set_wan(body)
            return self._json(result, 200 if result.get("ok") else 400)
        if path == "/lan":
            result, _ = set_lan(body)
            return self._json(result, 200 if result.get("ok") else 400)
        if path == "/device":
            result, _ = set_device(body)
            return self._json(result, 200 if result.get("ok") else 400)
        if path == "/apply":
            return self._json({"ok": True, "state": apply()})
        return self._json({"ok": False, "error": "not found"}, 404)


def serve(host="127.0.0.1", port=c.AXNET_PORT):
    c.ensure_dirs()
    srv = ThreadingHTTPServer((host, port), Handler)
    srv.daemon_threads = True
    c.log("api listening on %s:%d" % (host, port))
    srv.serve_forever()


def main(argv):
    c.ensure_dirs()
    cmd = argv[1] if len(argv) > 1 else "serve"
    if cmd == "apply":
        state = apply()
        print(json.dumps(state, indent=2))
    elif cmd == "state":
        print(json.dumps(snapshot(), indent=2))
    elif cmd == "serve":
        signal.signal(signal.SIGTERM, lambda *_: sys.exit(0))
        serve()
    elif cmd == "gen-psk":
        print(random_passphrase())
    else:
        print("usage: axnetd {serve|apply|state|gen-psk}")
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
