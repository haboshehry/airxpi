def ensure_bridge(cfg):
    lan = cfg["lan"]
    addr = lan["cidr"].split("/")[0]
    prefix = lan["cidr"].split("/")[1] if "/" in lan["cidr"] else "24"
    existing = c.interfaces()
    if BRIDGE not in existing:
        c.run(["ip", "link", "add", "name", BRIDGE, "type", "bridge"], timeout=15)
    # mDNS/AirPlay need multicast to be flooded, not snooped
    c.run(["ip", "link", "set", BRIDGE, "type", "bridge",
           "stp_state", "0", "forward_delay", "0", "mcast_snooping", "0"], timeout=15)
    c.run(["ip", "link", "set", BRIDGE, "up"], timeout=15)
    # drop addresses a previous configuration left behind, otherwise the panel
    # keeps reporting an address that no longer has a DHCP range behind it
    wanted = "%s/%s" % (addr, prefix)
    rc, out = c.run(["ip", "-4", "-o", "addr", "show", "dev", BRIDGE], timeout=10)
    if rc == 0:
        for line in out.splitlines():
            match = re.search(r"inet (\d+\.\d+\.\d+\.\d+/\d+)", line)
            if match and match.group(1) != wanted:
                c.run(["ip", "addr", "del", match.group(1), "dev", BRIDGE], timeout=10)
    c.run(["ip", "addr", "replace", wanted, "dev", BRIDGE], timeout=15)

    if lan.get("ethernet", True) and LAN_ETH in c.interfaces():
        c.run(["ip", "link", "set", LAN_ETH, "up"], timeout=15)
        c.run(["ip", "link", "set", LAN_ETH, "master", BRIDGE], timeout=15)
    return addr


def wifi_running():
    return c.service_active("hostapd")


def wait_for_unit(unit, seconds=8, active="active"):
    """Short bounded wait for a systemd unit - never the unit's own timeout."""
    deadline = time.time() + seconds
    state = ""
    while time.time() < deadline:
        rc, out = c.run(["systemctl", "is-active", unit], timeout=5)
        state = (out.strip().splitlines() or [""])[0]
        if state == active:
            return state
        time.sleep(0.35)
    return state


def unit_failure(unit):
    rc, out = c.run(["systemctl", "show", unit, "-p", "Result", "-p", "ExecMainStatus"], timeout=8)
    detail = " ".join(line.strip() for line in out.splitlines() if line.strip())
    rc, journal = c.run(["journalctl", "-u", unit, "-b", "-n", "20", "--no-pager"], timeout=10)
    lines = [line.strip() for line in journal.splitlines() if line.strip()]
    tail = " | ".join(lines[-4:])[:500]
    return (detail + (" - " + tail if tail else "")).strip()


def hostapd_start(cfg, changed):
    """Start or restart the AP, bounded, and record the real failure reason."""
    # systemd-rfkill restores the state saved in /var/lib/systemd/rfkill at
    # every boot; a single "blocked" entry there keeps wlan0 soft-blocked and
    # hostapd then fails with "interface wlan0 not found" - the hotspot never
    # comes up even though the config is perfect.
    c.run(["rfkill", "unblock", "wlan"], timeout=10)
    for state_file in ("/var/lib/systemd/rfkill/platform-3f300000.mmcnr:wlan",
                       "/var/lib/systemd/rfkill/platform-fe000000.mmcnr:wlan"):
        try:
            if os.path.exists(state_file):
                with open(state_file, "w", encoding="utf-8") as handle:
                    handle.write("0\n")
        except OSError:
            pass
    country = (cfg["wifi"].get("country") or "").upper()
    if c.valid_country(country):
        c.run(["iw", "reg", "set", country], timeout=10)
    rc, out = check_hostapd(HOSTAPD_CONF)
    if rc != 0:
        message = "hostapd rejected the configuration"
        detail = " ".join((out or "").split())[-300:]
        return False, (message + ": " + detail if detail else message)
    if c.service_active("hostapd"):
        if not changed:
            return True, ""
        # a config change needs a full restart; a plain re-apply must not drop
        # the clients (every udev hotplug calls apply())
        c.service_async("restart", "hostapd")
    else:
        c.run(["systemctl", "reset-failed", "hostapd"], timeout=10)
        c.service_async("start", "hostapd")
    state = wait_for_unit("hostapd", 10)
    if state == "active":
        # brcmfmac ships with 802.11 power save enabled; in AP mode that turns
        # the hotspot into a 5 Mbit/s stutter box, which is what "Wi-Fi sharing
        # is very slow" actually was.
        c.run(["iw", "dev", "wlan0", "set", "power_save", "off"], timeout=10)
        return True, ""
    return False, "hostapd is %s: %s" % (state or "unknown", unit_failure("hostapd"))


def wifi_mode(cfg):
    return (cfg["wifi"].get("mode") or "ap").lower()


def write_wpa_supplicant(cfg):
    """Write the STA profile used by bridge/extender mode."""
    up = cfg["wifi"].get("uplink") or {}
    ssid = str(up.get("ssid") or "").strip()
    psk = str(up.get("psk") or "")
    if not ssid:
        return False
    escaped = ssid.replace('"', '\\"')
    lines = [
        "# generated by axnetd (wifi.mode %s)" % wifi_mode(cfg),
        "ctrl_interface=DIR=/var/run/wpa_supplicant GROUP=netdev",
        "update_config=1",
        "country=%s" % (cfg["wifi"].get("country") or "US"),
        "",
        "network={",
        '\tssid="%s"' % escaped,
    ]
    if psk:
        lines.append('\tpsk="%s"' % psk.replace('"', '\\"'))
    else:
        lines.append("\tkey_mgmt=NONE")
    lines += ["\tscan_ssid=1", "}", ""]
    path = "/etc/wpa_supplicant/wpa_supplicant-wlan0.conf"
    if c.read_text(path) != "\n".join(lines):
        c.write_atomic(path, "\n".join(lines), 0o600)
        return True
    return False


def client_mode_apply(cfg, mode):
    """bridge = transparent L2 bridge over Wi-Fi; extender = STA + AP relay."""
    up = cfg["wifi"].get("uplink") or {}
    if not str(up.get("ssid") or "").strip():
        return {"ok": False, "error": "no upstream Wi-Fi (ssid) configured"}
    changed = write_wpa_supplicant(cfg)
    c.run(["rfkill", "unblock", "wlan"], timeout=10)
    c.run(["systemctl", "stop", "hostapd"], timeout=30)
    c.run(["systemctl", "disable", "--now", "dnsmasq"], timeout=30)
    if changed or not c.service_active("wpa_supplicant@wlan0"):
        c.run(["systemctl", "restart", "wpa_supplicant@wlan0"], timeout=40)
    else:
        c.run(["systemctl", "start", "wpa_supplicant@wlan0"], timeout=40)
    # wait for the association, then hand the link to the bridge
    deadline = time.time() + 30
    while time.time() < deadline:
        rc, out = c.run(["iw", "dev", "wlan0", "link"], timeout=10)
        if "Not connected" not in out and "Connected to" in out:
            break
        time.sleep(1.5)
    if "Connected to" not in out:
        return {"ok": False, "error": "could not join %s (check the passphrase)" % up.get("ssid")}
    c.run(["ip", "link", "set", "wlan0", "up"], timeout=10)
    c.run(["iw", "dev", "wlan0", "set", "power_save", "off"], timeout=10)
    c.run(["ip", "link", "set", "wlan0", "master", BRIDGE], timeout=15)
    c.run(["ip", "link", "set", BRIDGE, "up"], timeout=10)
    if mode == "extender":
        # single radio: rebroadcast on the same interface; brcmfmac rejects this
        # on most firmware revisions, so surface the reason instead of hanging
        c.run(["systemctl", "start", "hostapd"], timeout=40)
        if not c.service_active("hostapd"):
            return {"ok": False,
                    "error": "this radio cannot run AP and STA together: " + unit_failure("hostapd")}
    c.run(["systemctl", "restart", "dhcpcd"], timeout=40)
    return {"ok": True, "mode": mode}


def apply(cfg=None):
    """Reconcile the whole data path.  Safe to call repeatedly."""
    cfg = cfg or c.config()
    with LOCK:
        c.ensure_dirs()
        APPLY.update(running=True, started_at=int(time.time()), finished_at=0,
                     step="sysctl", error="", ok=None)
        try:
            write_sysctl()
        except Exception as exc:  # noqa: BLE001
            c.log("sysctl failed: %r" % (exc,))
        mode = wifi_mode(cfg)
        if mode in ("bridge", "extender"):
            result = client_mode_apply(cfg, mode)
            APPLY.update(running=False, finished_at=int(time.time()),
                         step="client-mode", ok=result.get("ok"),
                         error=result.get("error", ""))
            if not result.get("ok"):
                c.log("client mode %s failed: %s" % (mode, result.get("error")))
            return result
        # AP mode: keep 802.11 power save off on every reconcile, not only on
        # the hostapd start path (an unchanged config never restarts hostapd).
        c.run(["iw", "dev", "wlan0", "set", "power_save", "off"], timeout=10)

        APPLY["step"] = "dhcpcd"
        dhcpcd_changed = write_dhcpcd(cfg)
        APPLY["step"] = "bridge"
        lan_ip = ensure_bridge(cfg)
        APPLY["step"] = "dnsmasq"
        write_dnsmasq(cfg)

        wifi = cfg["wifi"]
        psk = wifi.get("passphrase") or ""
        psk_ok = c.valid_psk(psk) or psk == ""
        want_wifi = bool(wifi.get("enabled")) and psk_ok
        if not psk_ok:
            APPLY["error"] = "the access point needs a passphrase of 8-63 characters"
        if want_wifi:
            APPLY["step"] = "hostapd"
            changed = write_hostapd(cfg)
            ok, error = hostapd_start(cfg, changed)
            if not ok:
                APPLY["error"] = error
                c.log("apply: hostapd: %s" % error)
        else:
            APPLY["step"] = "hostapd-off"
            if c.service_active("hostapd"):
                c.service_async("stop", "hostapd")
            # hostapd puts wlan0 into the bridge; a stopped AP must not keep it
            if "wlan0" in c.interfaces():
                c.run(["ip", "link", "set", "wlan0", "nomaster"], timeout=10)

        APPLY["step"] = "nftables"
        nft_apply(cfg)
        APPLY["step"] = "avahi"
        if write_avahi(cfg):
            c.service_async("restart", "avahi-daemon")

        APPLY["step"] = "dnsmasq"
        c.run(["systemctl", "reset-failed", "dnsmasq"], timeout=10)
        if c.service_active("dnsmasq"):
            c.service("reload", "dnsmasq", timeout=15)
        else:
            c.service_async("start", "dnsmasq")

        if dhcpcd_changed:
            c.service_async("try-reload-or-restart", "dhcpcd")

        APPLY["step"] = "state"
        state = snapshot(cfg)
        APPLY["step"] = "done"
        APPLY["ok"] = not APPLY["error"]
        c.log("apply: wan=%s lan=%s/%s wifi=%s clients=%d%s" % (
            state["wan"]["iface"] or "-", BRIDGE, lan_ip,
            "on" if state["wifi"]["running"] else "off", len(state["clients"]),
            "" if APPLY["ok"] else " error=%s" % APPLY["error"][:160]))
        return state


def _apply_worker():
    while True:
        APPLY["pending"] = False
        try:
            apply()
        except Exception as exc:  # noqa: BLE001
            APPLY.update(running=False, ok=False, error=repr(exc),
                         finished_at=int(time.time()), step="failed")
            c.log("apply crashed: %r" % (exc,))
            return
        APPLY.update(running=False, finished_at=int(time.time()))
        if not APPLY.get("pending"):
            return


def start_apply():
    """Kick off a reconcile without blocking the HTTP request."""
    global APPLY_THREAD
    if APPLY.get("running"):
        APPLY["pending"] = True
        return {"running": True, "coalesced": True}
    APPLY_THREAD = threading.Thread(target=_apply_worker, daemon=True)
    APPLY_THREAD.start()
    return {"running": True, "coalesced": False}


def restart_ap():
    """Stop and start the access point, returning the exact error if it fails."""
    cfg = c.config()
    if not cfg["wifi"].get("enabled"):
        return {"ok": False, "error": "the access point is disabled"}
    if not c.valid_psk(cfg["wifi"].get("passphrase") or "") and cfg["wifi"].get("passphrase"):
        return {"ok": False, "error": "the passphrase must be 8-63 characters"}
    APPLY.update(running=True, started_at=int(time.time()), step="restart-ap", error="", ok=None)
    c.service("stop", "hostapd", timeout=25)
    c.run(["ip", "link", "set", "wlan0", "nomaster"], timeout=10)
    changed = write_hostapd(cfg)
    ok, error = hostapd_start(cfg, changed or True)
    APPLY.update(running=False, ok=ok, error=error, finished_at=int(time.time()),
                 step="restart-ap-done")
    return {"ok": ok, "error": error, "wifi": snapshot(cfg)["wifi"]}


def wifi_diag(cfg=None):
    """Everything needed to explain "my phone cannot join"."""
    cfg = cfg or c.config()
    diag = {}
    rc, out = check_hostapd(HOSTAPD_CONF)
    diag["config_check"] = {"ok": rc == 0, "output": (out or "")[-1200:]}
    rc, out = c.run(["systemctl", "show", "hostapd", "-p", "ActiveState", "-p",
                     "SubState", "-p", "Result", "-p", "ExecMainStatus"], timeout=10)
    diag["unit"] = " ".join(line.strip() for line in out.splitlines() if line.strip())
    for key, command in (
            ("wlan0", ["iw", "dev", "wlan0", "info"]),
            ("station_count", ["sh", "-c", "iw dev wlan0 station dump 2>/dev/null | grep -c '^Station'"]),
            ("regulatory", ["sh", "-c", "iw reg get | head -n 6"]),
            ("rfkill", ["rfkill", "list", "wlan"]),
            ("bridge", ["sh", "-c", "ip -br addr show br0; ip link show master br0 2>/dev/null"]),
            ("journal", ["journalctl", "-u", "hostapd", "-b", "-n", "25", "--no-pager"])):
        rc, out = c.run(command, timeout=12)
        diag[key] = (out or "")[-2500:]
    text = c.read_text(HOSTAPD_CONF)
    psk = cfg["wifi"].get("passphrase") or ""
    if psk:
        text = text.replace(psk, "***")
    diag["config"] = text
    return diag


