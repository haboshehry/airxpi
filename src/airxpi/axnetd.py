def ensure_bridge(cfg):
    lan = cfg["lan"]
    addr = lan["cidr"].split("/")[0]
    prefix = lan["cidr"].split("/")[1] if "/" in lan["cidr"] else "24"
    existing = c.interfaces()
    if BRIDGE not in existing:
        c.run(["ip", "link", "add", "name", BRIDGE, "type", "bridge"], timeout=15)
    # mDNS/AirPlay need multicast to be flooded, not snooped
    c.run(["ip", "link", "set", BRIDGE, "type", "bridge",
           "stp_state", "0", "forward_delay", "0", "mcast_snooping", "0"], timeout=15)
    c.run(["ip", "link", "set", BRIDGE, "up"], timeout=15)
    # drop addresses a previous configuration left behind, otherwise the panel
    # keeps reporting an address that no longer has a DHCP range behind it
    wanted = "%s/%s" % (addr, prefix)
    rc, out = c.run(["ip", "-4", "-o", "addr", "show", "dev", BRIDGE], timeout=10)
    if rc == 0:
        for line in out.splitlines():
            match = re.search(r"inet (\d+\.\d+\.\d+\.\d+/\d+)", line)
            if match and match.group(1) != wanted:
                c.run(["ip", "addr", "del", match.group(1), "dev", BRIDGE], timeout=10)
    c.run(["ip", "addr", "replace", wanted, "dev", BRIDGE], timeout=15)

    if lan.get("ethernet", True) and LAN_ETH in c.interfaces():
        c.run(["ip", "link", "set", LAN_ETH, "up"], timeout=15)
        c.run(["ip", "link", "set", LAN_ETH, "master", BRIDGE], timeout=15)
    return addr


def wifi_running():
    return c.service_active("hostapd")


def apply(cfg=None):
    """Reconcile the whole data path.  Safe to call repeatedly."""
    cfg = cfg or c.config()
    with LOCK:
        c.ensure_dirs()
        try:
            write_sysctl()
        except Exception as exc:  # noqa: BLE001
            c.log("sysctl failed: %r" % (exc,))

        dhcpcd_changed = write_dhcpcd(cfg)
        lan_ip = ensure_bridge(cfg)
        write_dnsmasq(cfg)

        wifi = cfg["wifi"]
        psk = wifi.get("passphrase") or ""
        psk_ok = c.valid_psk(psk) or psk == ""
        want_wifi = bool(wifi.get("enabled")) and psk_ok
        if want_wifi:
            changed = write_hostapd(cfg)
            country = (wifi.get("country") or "").upper()
            if c.valid_country(country):
                c.run(["iw", "reg", "set", country], timeout=15)
            if not c.service_active("hostapd"):
                c.run(["systemctl", "reset-failed", "hostapd"], timeout=15)
                c.service_async("start", "hostapd")
            elif changed:
                # a config change needs a full restart; a plain re-apply must
                # not drop the clients (every udev hotplug calls apply())
                c.service_async("restart", "hostapd")
        else:
            if c.service_active("hostapd"):
                c.service_async("stop", "hostapd")

        c.run(["systemctl", "reset-failed", "dnsmasq"], timeout=15)
        if c.service_active("dnsmasq"):
            c.service("reload", "dnsmasq", timeout=15)
        else:
            c.service_async("start", "dnsmasq")

        nft_apply(cfg)
        if write_avahi(cfg):
            c.service_async("restart", "avahi-daemon")

        if dhcpcd_changed:
            c.service_async("try-reload-or-restart", "dhcpcd")

        state = snapshot(cfg)
        c.log("apply: wan=%s lan=%s/%s wifi=%s clients=%d" % (
            state["wan"]["iface"] or "-", BRIDGE, lan_ip,
            "on" if state["wifi"]["running"] else "off", len(state["clients"])))
        return state


